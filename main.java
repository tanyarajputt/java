import java.util.*;


public class main {
    public static void main(String[] args) {
        //inputs
        Scanner sc = new Scanner(System.in);
        String name = sc.nextLine();// single word or token
        // to print whole line we have to use " nextLine" keyword
        // nextInt - use to print integer
        // nextFloat - use to print float
        System.out.println(name);
    }
    
}




